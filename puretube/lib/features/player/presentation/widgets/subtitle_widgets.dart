import 'package:flutter/material.dart';
import 'package:media_kit/media_kit.dart';

import '../../../../core/theme/app_theme.dart';
import '../providers/player_controller.dart';

/// Subtitle overlay at the bottom of the video.
class SubtitleOverlay extends StatelessWidget {
  final Player player;
  final PlayerController notifier;

  const SubtitleOverlay({
    super.key,
    required this.player,
    required this.notifier,
  });

  @override
  Widget build(BuildContext context) {
    return StreamBuilder<Duration>(
      stream: player.stream.position,
      builder: (_, snap) {
        final pos =
            snap.data ?? Duration.zero;
        final text =
            notifier.subtitleAt(pos);
        if (text == null || text.isEmpty) {
          return const SizedBox.shrink();
        }
        return Positioned(
          bottom: 70,
          left: 16,
          right: 16,
          child: Center(
            child: Container(
              padding:
                  const EdgeInsets.symmetric(
                      horizontal: 12,
                      vertical: 6),
              decoration: BoxDecoration(
                color: Colors.black
                    .withOpacity(0.5),
                borderRadius:
                    BorderRadius.circular(6),
              ),
              child: Text(
                text,
                textAlign: TextAlign.center,
                style: AppTheme.body.copyWith(
                  color: Colors.white,
                  fontSize: 15,
                  height: 1.4,
                ),
              ),
            ),
          ),
        );
      },
    );
  }
}

/// CC language picker bottom sheet.
class SubtitleSheet extends StatelessWidget {
  final PlayerController notifier;
  final PlayerUiState ui;

  const SubtitleSheet({
    super.key,
    required this.notifier,
    required this.ui,
  });

  static Future<void> show(
      BuildContext context,
      PlayerController notifier,
      PlayerUiState ui) {
    return showModalBottomSheet(
      context: context,
      builder: (_) => SubtitleSheet(
          notifier: notifier, ui: ui),
    );
  }

  @override
  Widget build(BuildContext context) {
    return SafeArea(
      child: Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          Padding(
            padding: const EdgeInsets.all(16),
            child: Text('Subtitles',
                style: AppTheme.subtitle),
          ),
          ListTile(
            title: const Text('Off'),
            trailing:
                ui.activeSubtitle == null
                    ? const Icon(Icons.check,
                        color:
                            AppTheme.primary)
                    : null,
            onTap: () {
              notifier.selectSubtitle(null);
              Navigator.pop(context);
            },
          ),
          if (ui.subtitleTracks.isEmpty)
            Padding(
              padding: const EdgeInsets.all(
                  16),
              child: Text(
                  'No subtitles available',
                  style: AppTheme.body.copyWith(
                      color: AppTheme
                          .textSecondary)),
            ),
          Flexible(
            child: ListView.builder(
              shrinkWrap: true,
              itemCount:
                  ui.subtitleTracks.length,
              itemBuilder: (_, i) {
                final t =
                    ui.subtitleTracks[i];
                final active =
                    ui.activeSubtitle
                            ?.languageCode ==
                        t.languageCode;
                return ListTile(
                  title: Text(t.language,
                      style: AppTheme.body),
                  subtitle: t.isAutoGenerated
                      ? Text('Auto-generated',
                          style: AppTheme
                              .caption
                              .copyWith(
                                  color: AppTheme
                                      .textSecondary))
                      : null,
                  trailing: active
                      ? const Icon(Icons.check,
                          color:
                              AppTheme.primary)
                      : null,
                  onTap: () {
                    notifier
                        .selectSubtitle(t);
                    Navigator.pop(context);
                  },
                );
              },
            ),
          ),
        ],
      ),
    );
  }
}
