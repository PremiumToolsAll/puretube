import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../providers/player_controller.dart';

/// CC language picker bottom sheet.
class SubtitleSheet extends ConsumerWidget {
  const SubtitleSheet({super.key});

  static Future<void> show(BuildContext context) {
    return showModalBottomSheet(
      context: context,
      builder: (_) => const SubtitleSheet(),
    );
  }

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final ui = ref.watch(playerControllerProvider);
    final notifier =
        ref.read(playerControllerProvider.notifier);
    final accent = Theme.of(context).colorScheme.primary;

    return SafeArea(
      child: Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          const Padding(
            padding: EdgeInsets.all(16),
            child: Text('Subtitles',
                style: TextStyle(
                    fontWeight: FontWeight.bold,
                    fontSize: 16)),
          ),
          ListTile(
            title: const Text('Off'),
            trailing: ui.activeSubtitle == null
                ? Icon(Icons.check, color: accent)
                : null,
            onTap: () {
              notifier.selectSubtitle(null);
              Navigator.pop(context);
            },
          ),
          if (ui.subtitleTracks.isEmpty)
            const Padding(
              padding: EdgeInsets.all(16),
              child: Text('No subtitles available',
                  style: TextStyle(color: Colors.grey)),
            ),
          Flexible(
            child: ListView.builder(
              shrinkWrap: true,
              itemCount: ui.subtitleTracks.length,
              itemBuilder: (_, i) {
                final t = ui.subtitleTracks[i];
                final active =
                    ui.activeSubtitle?.languageCode ==
                        t.languageCode;
                return ListTile(
                  title: Text(t.language),
                  subtitle: t.isAutoGenerated
                      ? const Text('Auto-generated',
                          style: TextStyle(
                              color: Colors.grey,
                              fontSize: 12))
                      : null,
                  trailing: active
                      ? Icon(Icons.check,
                          color: accent)
                      : null,
                  onTap: () {
                    notifier.selectSubtitle(t);
                    Navigator.pop(context);
                  },
                );
              },
            ),
          ),
        ],
      ),
    );
  }
}
